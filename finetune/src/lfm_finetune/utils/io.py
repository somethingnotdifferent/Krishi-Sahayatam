"""Filesystem helpers: atomic writes and guaranteed JSON/YAML serialisation."""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any

from .errors import PipelineError
from .logging import get_logger

log = get_logger("utils.io")


def ensure_dir(path: Path | str) -> Path:
    """``mkdir -p`` that returns the Path."""
    p = Path(path)
    p.mkdir(parents=True, exist_ok=True)
    return p


def atomic_write_text(path: Path | str, text: str, *, encoding: str = "utf-8") -> Path:
    """Write via a temp file + ``os.replace`` so readers never see a partial file.

    Matters for resumable runs: a checkpoint directory is inspected by other
    processes while training may be writing into it.
    """
    p = Path(path)
    ensure_dir(p.parent)
    fd, tmp = tempfile.mkstemp(dir=str(p.parent), prefix=f".{p.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding=encoding) as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, p)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    return p


def _default(obj: Any) -> Any:
    """Fallback encoder for pathlib / dataclass / set / numpy scalars."""
    if isinstance(obj, Path):
        return str(obj)
    if isinstance(obj, set | frozenset):
        return sorted(obj)
    if hasattr(obj, "to_dict"):
        return obj.to_dict()
    if hasattr(obj, "__dataclass_fields__"):
        from dataclasses import asdict

        return asdict(obj)
    item = getattr(obj, "item", None)  # numpy scalars
    if callable(item):
        return item()
    raise TypeError(f"Object of type {type(obj).__name__} is not JSON serialisable")


def write_json(path: Path | str, obj: Any, *, indent: int = 2, sort_keys: bool = True) -> Path:
    """Atomically write pretty JSON that always round-trips."""
    try:
        text = json.dumps(obj, indent=indent, sort_keys=sort_keys, ensure_ascii=False, default=_default)
    except TypeError as exc:
        raise PipelineError(f"Cannot serialise report to JSON: {exc}") from exc
    return atomic_write_text(path, text + "\n")


def read_json(path: Path | str) -> Any:
    p = Path(path)
    if not p.exists():
        raise PipelineError(
            f"Expected JSON file not found: {p}",
            hint="Run the earlier pipeline stage first (e.g. `lfm-finetune prepare`).",
        )
    with p.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def write_jsonl(path: Path | str, records: list[Any]) -> Path:
    """Atomically write a JSONL file."""
    body = "\n".join(json.dumps(r, ensure_ascii=False, default=_default) for r in records)
    return atomic_write_text(path, body + ("\n" if body else ""))


def read_yaml(path: Path | str) -> Any:
    import yaml

    p = Path(path)
    if not p.exists():
        raise PipelineError(
            f"Configuration file not found: {p}",
            hint="Pass an existing path with --config, or run `lfm-finetune config-init`.",
        )
    with p.open("r", encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def write_yaml(path: Path | str, obj: Any) -> Path:
    import yaml

    header = "# Auto-generated by lfm-finetune. Captures the fully-resolved\n" \
             "# configuration so this run can be reproduced without the source YAML.\n"
    text = yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, default_flow_style=False)
    return atomic_write_text(path, header + text)


def dir_size_bytes(path: Path | str) -> int:
    """Recursive on-disk size, used for artifact accounting."""
    base = Path(path)
    if not base.exists():
        return 0
    if base.is_file():
        return base.stat().st_size
    return sum(f.stat().st_size for f in base.rglob("*") if f.is_file())